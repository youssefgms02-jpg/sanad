def main():
    db = SessionLocal()
    demoted = updated = inserted = 0
    audited_keys = {(item["category"], item["name"]) for item in AUDITED_SERVICES}
    try:
        # Remove publication status from the earlier pilot where full service
        # details have not yet been individually checked.
        for category, name in PILOT_NAMES:
            if (category, name) in audited_keys:
                continue
            rows = db.query(Service).filter(
                Service.category == category,
                Service.name == name,
                Service.status == "published",
            ).all()
            for row in rows:
                row.status = "draft"
                row.last_reviewed = None
                demoted += 1

        for item in AUDITED_SERVICES:
            row = db.query(Service).filter(
                Service.category == item["category"],
                Service.name == item["name"],
            ).first()

            values = {
                **item,
                "status": "published",
                "last_reviewed": datetime.now(timezone.utc),
            }

            if row:
                for field, value in values.items():
                    setattr(row, field, value)
                updated += 1
            else:
                db.add(Service(**values))
                inserted += 1

        db.commit()
        print(f"Audit batch 01 complete. Published/updated: {updated}, inserted: {inserted}, returned to draft pending review: {demoted}.")
        print(f"Individually researched services in this batch: {len(AUDITED_SERVICES)}")
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()

if __name__ == "__main__":
    main()
