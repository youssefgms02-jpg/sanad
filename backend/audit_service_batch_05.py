def main():
    db = SessionLocal()
    updated = inserted = 0
    try:
        for item in AUDITED_SERVICES:
            row = db.query(Service).filter(
                Service.category == item["category"],
                Service.name == item["name"],
            ).first()
            values = {
                **item,
                "status": "published",
                "last_reviewed": datetime.now(timezone.utc),
            }
            if row:
                for field, value in values.items():
                    setattr(row, field, value)
                updated += 1
            else:
                db.add(Service(**values))
                inserted += 1

        db.commit()
        print(
            f"Audit batch 05 complete. Published/updated: {updated}, "
            f"inserted: {inserted}. Individually researched services: {len(AUDITED_SERVICES)}."
        )
        print("All five records include descriptions, authority, eligibility, documents, steps and official sources.")
        print("Fees and timelines are included only where stated by the official source; variable items are not guessed.")
        print("All other services remain unchanged; no records deleted.")
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()

if __name__ == "__main__":
    main()
