REQUIRED_FIELDS = ("description", "authority", "eligibility", "documents", "steps", "official_source")

def main():
    db = SessionLocal()
    try:
        found, missing = [], []
        for item in SERVICES:
            row = db.query(Service).filter(
                Service.category == item["category"],
                Service.name == item["name"],
            ).first()
            if row is None:
                missing.append(f'{item["category"]}: {item["name"]}')
            else:
                found.append((row, item))

        if missing:
            print("ABORTED: no database changes were made.")
            print("Exact target records not found:")
            for name in missing:
                print(f" - {name}")
            return

        incomplete = []
        for _, item in found:
            absent = [field for field in REQUIRED_FIELDS if not str(item.get(field, "")).strip()]
            if absent:
                incomplete.append((item["name"], absent))
        if incomplete:
            print("ABORTED: validation failed; no database changes were made.")
            for name, fields in incomplete:
                print(f" - {name}: missing {', '.join(fields)}")
            return

        reviewed_at = datetime.now(timezone.utc)
        for row, item in found:
            for field in REQUIRED_FIELDS:
                setattr(row, field, item[field])
            row.status = "published"
            row.last_reviewed = reviewed_at

        db.commit()
        print("SANAD AUDIT BATCH 09 COMPLETE")
        print(f"Published/updated: {len(found)}")
        print("Inserted: 0")
        print("Deleted: 0")
        print("All exact targets were found and validated before the transaction.")
        print("All updated records include details, official sources, and review timestamps.")
        print("Center programs vary by center, age, and assessment; health-insurance rollout is governorate-dependent.")
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()

if __name__ == "__main__":
    main()
