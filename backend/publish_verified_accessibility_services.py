def main():
    db: Session = SessionLocal()
    try:
        for service_id, fields in VERIFIED.items():
            service = db.query(Service).filter(Service.id == service_id).first()
            if service is None:
                raise RuntimeError(f"Service ID {service_id} not found; nothing committed.")
            if service.name != fields["name"]:
                raise RuntimeError(
                    f"Service ID {service_id} name mismatch: {service.name!r}; nothing committed."
                )
            if not all(str(fields[key]).strip() for key in (
                "authority", "eligibility", "documents", "steps", "official_source"
            )):
                raise RuntimeError(f"Required publication fields missing for ID {service_id}.")
            for key, value in fields.items():
                setattr(service, key, value)
            service.status = "published"
            service.last_reviewed = REVIEWED_AT

        db.commit()
        print(f"Published {len(VERIFIED)} verified services:")
        for service_id in VERIFIED:
            print(f"- ID {service_id}: {db.query(Service).filter(Service.id == service_id).first().name}")
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()


if __name__ == "__main__":
    main()
