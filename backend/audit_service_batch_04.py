def main():
    db = SessionLocal()
    updated = inserted = 0
    try:
        for item in AUDITED_SERVICES:
            row = db.query(Service).filter(
                Service.category == item["category"],
                Service.name == item["name"],
            ).first()

            values = {
                **item,
                "status": "draft",
                "last_reviewed": None,
            }
            if row:
                for field, value in values.items():
                    setattr(row, field, value)
                updated += 1
            else:
                db.add(Service(**values))
                inserted += 1

        db.commit()
        print(
            f"Audit batch 04 complete. Audited: {len(AUDITED_SERVICES)}; "
            f"updated: {updated}; inserted: {inserted}; kept as drafts: {len(AUDITED_SERVICES)}."
        )
        print("Reason: official existence confirmed, but individual current eligibility/documents are incomplete.")
        print("No unreviewed records changed. No records deleted.")
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()

if __name__ == "__main__":
    main()
