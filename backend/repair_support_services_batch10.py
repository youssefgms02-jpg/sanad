def main():
    if len(UPDATES) != 8:
        raise SystemExit("Expected exactly eight updates. No database changes made.")

    db = SessionLocal()
    try:
        rows = []
        problems = []
        for service_id, item in UPDATES.items():
            row = db.query(Service).filter(Service.id == service_id).first()
            if row is None:
                problems.append(f"Missing ID {service_id}")
                continue
            if row.name != item["name"] or row.category != "support":
                problems.append(
                    f"Target mismatch at ID {service_id}: {row.category} | {row.name}"
                )
            rows.append((row, item))

        if problems:
            print("Preflight failed; no records were changed.")
            for problem in problems:
                print("-", problem)
            return

        now = datetime.now(timezone.utc)
        for row, item in rows:
            for field in ("description", "authority", "eligibility", "documents", "steps", "official_source"):
                setattr(row, field, item[field])
            row.last_reviewed = now

        db.commit()
        print("SUPPORT SERVICES REPAIR COMPLETE")
        print("Updated existing records:", len(rows))
        print("Publication statuses preserved; no records inserted or deleted.")
        for row, _ in rows:
            print(f"{row.id}: {row.name} [{row.status}]")
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()


if __name__ == "__main__":
    main()
